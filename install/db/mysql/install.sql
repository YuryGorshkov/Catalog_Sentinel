CREATE TABLE IF NOT EXISTS b_gcs_scan (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NOT NULL,
    FINISHED_AT DATETIME NULL,
    IMPORTED_AT DATETIME NULL,
    MODE VARCHAR(16) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    DECISION VARCHAR(16) NULL,
    SOURCE_KEY CHAR(64) NOT NULL,
    SOURCE_LABEL VARCHAR(255) NOT NULL,
    DOCUMENT_KIND VARCHAR(32) NOT NULL,
    FILE_NAME VARCHAR(255) NOT NULL,
    PATH_HASH CHAR(64) NOT NULL,
    CONTENT_HASH CHAR(64) NULL,
    FILE_SIZE BIGINT UNSIGNED NOT NULL,
    FILE_MTIME BIGINT NULL,
    IDENTITY_KEY CHAR(64) NOT NULL,
    POLICY_VERSION INT UNSIGNED NOT NULL,
    ANALYZER_SCHEMA_VERSION INT UNSIGNED NOT NULL,
    METRICS_JSON MEDIUMTEXT NOT NULL,
    SAMPLES_JSON MEDIUMTEXT NOT NULL,
    WARNINGS_JSON TEXT NOT NULL,
    RULE_RESULTS_JSON MEDIUMTEXT NOT NULL,
    ERROR_CODE VARCHAR(100) NULL,
    ERROR_MESSAGE VARCHAR(2000) NULL,
    DURATION_MS INT UNSIGNED NULL,
    MEMORY_DELTA_BYTES BIGINT NULL,
    IS_DRY_RUN CHAR(1) NOT NULL DEFAULT 'N',
    CACHE_UNTIL DATETIME NULL,
    PRIMARY KEY (ID),
    INDEX ix_gcs_scan_created (CREATED_AT),
    INDEX ix_gcs_scan_status_created (STATUS, CREATED_AT),
    INDEX ix_gcs_scan_decision_created (DECISION, CREATED_AT),
    INDEX ix_gcs_scan_source_kind_created (SOURCE_KEY, DOCUMENT_KIND, CREATED_AT),
    INDEX ix_gcs_scan_identity_policy_cache (IDENTITY_KEY, POLICY_VERSION, CACHE_UNTIL),
    INDEX ix_gcs_scan_dry_created (IS_DRY_RUN, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS b_gcs_violation (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    SCAN_ID BIGINT UNSIGNED NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    RULE_CODE VARCHAR(100) NOT NULL,
    OUTCOME VARCHAR(16) NOT NULL,
    REASON_CODE VARCHAR(100) NOT NULL,
    ACTUAL_JSON TEXT NOT NULL,
    THRESHOLDS_JSON TEXT NOT NULL,
    BASELINE_JSON TEXT NULL,
    SAMPLE_JSON TEXT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY ux_gcs_violation_scan_rule_reason (SCAN_ID, RULE_CODE, REASON_CODE),
    INDEX ix_gcs_violation_scan (SCAN_ID),
    INDEX ix_gcs_violation_rule (RULE_CODE),
    INDEX ix_gcs_violation_outcome (OUTCOME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS b_gcs_baseline_sample (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CREATED_AT DATETIME NOT NULL,
    SOURCE_KEY CHAR(64) NOT NULL,
    DOCUMENT_KIND VARCHAR(32) NOT NULL,
    ANALYZER_SCHEMA_VERSION INT UNSIGNED NOT NULL,
    SCAN_ID BIGINT UNSIGNED NOT NULL,
    ORIGIN VARCHAR(16) NOT NULL,
    ACCEPTED_BY INT NULL,
    METRICS_JSON MEDIUMTEXT NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY ux_gcs_baseline_scan_origin (SCAN_ID, ORIGIN),
    INDEX ix_gcs_baseline_lookup (SOURCE_KEY, DOCUMENT_KIND, ANALYZER_SCHEMA_VERSION, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS b_gcs_notification_state (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    SOURCE_KEY CHAR(64) NOT NULL,
    RULE_CODE VARCHAR(100) NOT NULL,
    CHANNEL VARCHAR(32) NOT NULL,
    LAST_SENT_AT DATETIME NOT NULL,
    LAST_SCAN_ID BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY ux_gcs_notification_scope (SOURCE_KEY, RULE_CODE, CHANNEL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
